CARD_1159 = re.compile(r'มาตรา ๑๑๖๐(</(?:div|h5)>\s*<div[^>]*>🔒 บทสรุปแห่งความศักดิ์สิทธิ์)')


def rw(path, fn):
    s = io.open(path, encoding='utf-8').read()
    s2 = fn(s)
    io.open(path, 'w', encoding='utf-8').write(s2)


def replace(s, old, new, n, where):
    assert s.count(old) == n, (where, old[:50], s.count(old))
    return s.replace(old, new)


def main():
    old_site = io.open(OLD, encoding='utf-8').read()
    for o, n in PREAMBLE:
        old_site = replace(old_site, o, n, 1, 'preamble')
    for tab, o, n, cnt in TABS:
        old_site = replace(old_site, o, n, old_site.count(o) if cnt > 1 else 1, OLD + ':' + tab)
        rw('src/tabs/%s.html' % tab, lambda s, o=o, n=n, cnt=cnt, tab=tab: replace(s, o, n, cnt, tab))
    old_site, k = CARD_1159.subn(r'มาตรา ๑๑๕๙\1', old_site)
    assert k == 1, k
    rw('src/tabs/supreme-assembly-tab.html', lambda s: (lambda r: (r[0] if r[1] == 1 else None))(CARD_1159.subn(r'มาตรา ๑๑๕๙\1', s)))
    io.open(OLD, 'w', encoding='utf-8').write(old_site)
    print('applied')


if __name__ == '__main__':
    main()
