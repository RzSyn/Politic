def once(s, old, new, where):
    assert s.count(old) == 1, (where, old[:60], s.count(old))
    return s.replace(old, new)


def main():
    site = io.open(OLD, encoding='utf-8').read()
    for o, n in CHARTER:
        site = once(site, o, n, 'charter')
    for tab, o, n in TABS:
        site = once(site, o, n, OLD + ':' + tab)
        p = 'src/tabs/%s.html' % tab
        s = io.open(p, encoding='utf-8').read()
        io.open(p, 'w', encoding='utf-8').write(once(s, o, n, p))
    io.open(OLD, 'w', encoding='utf-8').write(site)
    print('applied %d charter and %d tab edits' % (len(CHARTER), len(TABS)))


if __name__ == '__main__':
    main()
