def add_tab(tid, icon, label, title, lead, blocks, after, accent):
    new = '<div id="%s" class="db-tab-content">\n%s\n</div>\n' % (tid, tb.new_render(icon, title, lead, blocks))
    old = '\n<div id="%s" class="db-tab-content">\n%s\n</div>' % (tid, tb.old_render(icon, title, lead, blocks, accent=accent))
    assert tb.balanced(new) and tb.balanced(old) and '%%' not in new + old
    h = json.loads(rd('src/hub.json'))
    for g in h:
        ids = [t['id'] for t in g['topics']]
        if after in ids:
            assert tid not in ids
            g['topics'].insert(ids.index(after) + 1, {'id': tid, 'icon': icon, 'label': label})
    wr('src/hub.json', json.dumps(h, ensure_ascii=False, indent=2) + '\n')
    wr('src/tabs/%s.html' % tid, new)
    s = rd(OLD)
    assert 'id="%s"' % tid not in s
    i = s.index("switchTab('%s', this)" % after)
    b1 = s.index('</button>', i) + len('</button>')
    s = s[:b1] + ('\n          <button class="db-tab-btn" onclick="switchTab(\'%s\', this)" '
                  'style="border-color:rgba(%s,0.6);color:%s;">%s %s</button>') % (tid, accent[1], accent[0], icon, label) + s[b1:]
    p0 = s.index('<div id="%s"' % after)
    end = tb.div_span(s, p0)
    assert s.index('<section id="history_and_pms"') < end < s.index('</section>', end)
    s = s[:end] + old + s[end:]
    assert s.count('id="%s"' % tid) == 1
    wr(OLD, s)


