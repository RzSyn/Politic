def append_blocks(blocks, accent):
    def fn(t, site):
        html = tb.new_render('', '', '', blocks) if site == 'new' else tb.old_render('', '', '', blocks, accent=accent)
        # keep only the sections, not the empty header the renderers add
        if site == 'new':
            body = html[html.index('</header>') + len('</header>'):html.rindex('</div>')]
            body = '<div class="nwc">' + body + '</div>'
        else:
            k = html.index('</div></div>', html.index('<h3')) + len('</div></div>')
            body = '<div style="margin-top:24px;">' + html[k:html.rindex('</div>')] + '</div>'
        assert tb.balanced(body)
        e = t.rindex('</div>')               # inside the tab's outer div
        return t[:e] + body + '\n' + t[e:]
    return fn


