def apply(seg, pairs, tag):
    for a, b in pairs:
        c = seg.count(a)
        assert c >= 1, (tag, a[:60])
        seg = seg.replace(a, b)
    return seg

def rd(p): return io.open(p, encoding='utf-8').read()
def wr(p, s): io.open(p, 'w', encoding='utf-8', newline='').write(s)

