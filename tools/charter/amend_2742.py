def paras_html(paras, first_prefix=''):
    out = []
    for k, p in enumerate(paras):
        p = th(p)
        m = re.match(r'^(\([๐-๙]+\))\s*(.*)$', p)
        if m:
            out.append('<p class="list-item"><span class="list-num">%s</span> %s</p>' % (m.group(1), E(m.group(2), quote=False)))
        elif k == 0 and first_prefix:
            out.append('<p class="article-text">%s%s</p>' % (first_prefix, E(p, quote=False)))
        else:
            out.append('<p class="sub-para">%s</p>' % E(p, quote=False))
    return '\n'.join(out)


def card(no, head, paras):
    aid = no.replace('/', '_')
    body = paras_html(paras, '<span class="art-num">มาตรา %s</span> %s: ' % (th(no), E(head)))
    body += '\n' + NOTE % ('มาตรานี้เพิ่มโดย%s มาตรา %s' % (ACT, th(str(SECTION_OF[no]))))
    return ('<div class="article-card" id="art_%s" data-origin="later">\n\n\n  <div class="article-header">\n\n\n'
            '    <span class="badge badge-later">%s</span>\n\n\n    \n\n\n  </div>\n\n\n'
            '  <div class="article-body">%s</div>\n\n\n  \n\n\n</div>') % (aid, BADGE, body)


